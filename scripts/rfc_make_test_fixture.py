"""Regenerate tests/fixtures/library: a tiny, offline sample library.

Copies a handful of RFCs byte-for-byte from the local mirror (unmodified,
as the IETF Trust permits redistributing whole RFCs), and trims the RFC
index and the bulk errata feed to the documents the tests use. Run from
the repo root with a synced library:

    python scripts/make_test_fixture.py [--errata path/to/errata.json]
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data"
OUT = ROOT / "tests" / "fixtures" / "library"

# With files: an RFCXML document (8651), a ToC-structured ABNF spec (5234),
# a short ABNF update (7405), a 1980 RFC without a ToC (768), the two BCP 14
# documents. Catalog-only: TCP's obsolete chain (793 -> 9293).
FILES = {"RFC8651": ("txt", "xml"), "RFC5234": ("txt",), "RFC7405": ("txt",),
         "RFC768": ("txt",), "RFC2119": ("txt",), "RFC8174": ("txt",)}
CATALOG_ONLY = {"RFC793", "RFC9293", "RFC879", "RFC2873", "RFC6093",
                "RFC6528", "RFC6691", "RFC1122", "RFC4234", "RFC2234",
                "RFC3986"}
ALIASES = {"BCP14", "STD68"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--errata", type=Path,
                    help="bulk errata.json (default: download skipped, "
                         "existing fixture errata kept)")
    a = ap.parse_args()
    keep = set(FILES) | CATALOG_ONLY | ALIASES
    if OUT.exists():
        shutil.rmtree(OUT / "mirror", ignore_errors=True)
    (OUT / "mirror" / "rfc").mkdir(parents=True, exist_ok=True)
    (OUT / "meta").mkdir(parents=True, exist_ok=True)
    for doc, fmts in FILES.items():
        for fmt in fmts:
            name = f"{doc.lower()}.{fmt}"
            shutil.copyfile(SRC / "mirror" / "rfc" / name,
                            OUT / "mirror" / "rfc" / name)

    xml = (SRC / "meta" / "rfc-index.xml").read_text("utf-8")
    head = xml[:xml.index("<bcp-entry>")]
    entries = re.findall(r"<(bcp|rfc|std|fyi)-entry>.*?</\1-entry>", xml,
                         re.S)
    blocks = re.findall(r"<(?:bcp|rfc|std|fyi)-entry>.*?</(?:bcp|rfc|std|fyi)"
                        r"-entry>", xml, re.S)
    assert len(entries) == len(blocks)
    kept = []
    for b in blocks:
        m = re.search(r"<doc-id>(\w+)</doc-id>", b)
        if m and m.group(1) in keep:
            kept.append(b)
    (OUT / "meta" / "rfc-index.xml").write_text(
        head + "\n".join(kept) + "\n</rfc-index>\n", "utf-8")

    if a.errata:
        feed = json.loads(a.errata.read_text("utf-8"))
        rows = [e for e in feed if e.get("doc-id") in keep]
        (OUT / "errata.json").write_text(json.dumps(rows, indent=1), "utf-8")
    (OUT / "README.md").write_text(
        "Sample library for tests (generated by scripts/make_test_fixture.py).\n"
        "RFC files are unmodified copies from rfc-editor.org; RFCs are\n"
        "published under the IETF Trust Legal Provisions "
        "(https://trustee.ietf.org/license-info).\n", "utf-8")
    print(f"{len(kept)} index entries, files: {sorted(FILES)}")


if __name__ == "__main__":
    main()
